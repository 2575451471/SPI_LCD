#define FONT8X8_COUNT \
    (sizeof(Font8x8_Table) / sizeof(Font8x8_Table[0]))


/*********************************************************************
 * @fn      Font8x8_Get
 *
 * @brief   Find ASCII font bitmap
 *
 * @param   ch
 *
 * @return  pointer to 8-byte bitmap
 *********************************************************************/
const uint8_t *Font8x8_Get(char ch)
{
    uint16_t i;


    /*
     * 暂时自动把小写转成大写。
     *
     * 例如:
     *
     * hello -> HELLO
     */
    if(ch >= 'a' && ch <= 'z')
    {
        ch = ch - 'a' + 'A';
    }


    for(i = 0; i < FONT8X8_COUNT; i++)
    {
        if(Font8x8_Table[i].ch == ch)
        {
            return Font8x8_Table[i].data;
        }
    }


    /*
     * 找不到字符时返回空格
     */
    return Font8x8_Table[0].data;
}