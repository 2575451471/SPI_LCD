#define FONT_CN16_COUNT \
    (sizeof(FontCN16_Table) / sizeof(FontCN16_Table[0]))


/*********************************************************************
 * @fn      FontCN16_Get
 *
 * @brief   Get 16x16 Chinese font bitmap
 *********************************************************************/
const uint8_t *FontCN16_Get(uint16_t code)
{
    uint16_t i;


    for(i = 0; i < FONT_CN16_COUNT; i++)
    {
        if(FontCN16_Table[i].code == code)
        {
            return FontCN16_Table[i].data;
        }
    }


    return 0;
}